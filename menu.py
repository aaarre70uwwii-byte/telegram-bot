def register_menu_handler(bot, active_groups):
    @bot.message_handler(content_types=['text'], chat_types=['group','supergroup'])
    def show_menu(m):
        if m.chat.id not in active_groups: return
        text = m.text.strip()
        
        if text == "الاوامر":
            menu_text = """📜 **قائمة اوامر البوت كاملة**

**1. اوامر الادمنيه `m1`**
`رتبتي` 
`رفع` `تنزيل` - رد على العضو
`كتم` `الغاء الكتم` - بالرد
`حظر` `الغاء الحظر` `طرد` - بالرد
`مسح 10` - يمسح 10 رسائل
`تنزيل الكل` - للمالك فقط

**2. اوامر الاعدادات `m2`**
`الاعدادات` 
`الاعدادات خاص` - يرسل لك خاص
`همس النص` - رد على العضو

**3. اوامر الحماية `m3`**
`قفل الروابط` `فتح الروابط`
`قفل الصور` `فتح الصور`
`قفل السب` `فتح السب`
`قفل التكرار` `فتح التكرار`
`قفل البوتات بالطرد` `فتح البوتات بالطرد`
`الحماية` - يعرض حالة الحماية

**4. اوامر التسليه `m4`**
`نكتة` `صراحة` `تحدي` `رتبي`
`نسبه الحب` - بالرد
`تتزوجني` `قبول` `رفض` `طلاق` - بالرد
`زوجي` `زوجتي`
`رفع هطف` `رفع بثر` `رفع حمار` `رفع كلب` الخ - بالرد
`رفع بقلبي` `تنزيل من قلبي` - بالرد
`اكتموه` - تصويت 3 مرات للكتم
`تفعيل التسليه` `تعطيل التسليه` - للادمن
`تفعيل زوجني` `تعطيل زوجني` - للادمن
`مسح رتب التسليه` - للادمن

━━━━━━━━━━━━
**اوامر عامة:**
`تفعيل` - لتفعيل البوت
`تعطيل` - لتعطيل البوت
`الاوامر` - لعرض هذه القائمة
"""
            bot.reply_to(m, menu_text, parse_mode="Markdown")
        
        elif text == "المطور":
            bot.reply_to(m, "👨‍💻 المطور: انت\nالبوت: شغال 100% كتابه")
